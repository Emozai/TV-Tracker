// Builds dist/worker.js from ../apps-script (Code.gs + Index.html + PasswordSetup.html) and src/.
// Run: node build.mjs        (wrangler runs it automatically on deploy)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const gas = join(here, '..', 'apps-script');
const read = p => readFileSync(p, 'utf8');
const forTest = process.argv.includes('--test');   // node test build: no "cloudflare:workers" import

const code = read(join(gas, 'Code.gs'));
const pageShim = read(join(here, 'src', 'page-shim.js'));
const photo = existsSync(join(gas, 'Photo.html')) ? read(join(gas, 'Photo.html')).trim() : '';

function preparePage(html) {
  html = html
    .replace(/<\?!=\s*include\(['"]Photo['"]\)\s*\?>/g, photo)
    .replace(/<\?=\s*ScriptApp\.getService\(\)\.getUrl\(\)\s*\?>/g, '__SERVICE_URL__')
    // Final Check lives in a separate Apps Script file that is not part of this project.
    .replace(/<a class="finalCheckLink"[\s\S]*?<\/a>/, '');
  const left = html.match(/<\?[\s\S]*?\?>/);
  if (left) throw new Error('Unsupported Apps Script template tag in page: ' + left[0].slice(0, 80));
  const tag = '<script>' + pageShim + '</script>';
  return /<head[^>]*>/i.test(html) ? html.replace(/<head[^>]*>/i, m => m + tag) : tag + html;
}
const pages = {
  Index: preparePage(read(join(gas, 'Index.html'))),
  PasswordSetup: preparePage(read(join(gas, 'PasswordSetup.html')))
};

const names = [...new Set([...code.matchAll(/^function\s+([A-Za-z_$][\w$]*)\s*\(/gm)].map(m => m[1]))];
const table = 'const GAS_FUNCTIONS_ = {\n' + names.map(n => '  ' + n + ': typeof ' + n + " === 'function' ? " + n + ' : undefined').join(',\n') + '\n};\n';

function bundle(kind, test) {
  const parts = [
    '// GENERATED by cloudflare/build.mjs from apps-script/Code.gs + Index.html + PasswordSetup.html. Do not edit by hand.',
    kind === 'do' ? (test ? 'class DurableObject { constructor(ctx, env) { this.ctx = ctx; this.env = env; } }' : 'import { DurableObject } from "cloudflare:workers";')
      : '// Cabin TV Tracker — paste this whole file into your Worker (Edit code), then add a D1 binding named DB. See README.',
    read(join(here, 'src', 'gas-shim.js')),
    read(join(here, 'src', 'store.js')),
    'const HTML_FILES_ = ' + JSON.stringify(pages) + ';',
    '// ======================================= Code.gs =======================================',
    code,
    '// ===================================== end Code.gs =====================================',
    table,
    read(join(here, 'src', 'routes.js')),
    read(join(here, 'src', kind === 'do' ? 'entry.js' : 'entry-d1.js')),
    test ? 'export { RT, M, ST_, BACKEND, shimBegin_, shimFlush_, GAS_FUNCTIONS_, runDueTriggers_, xlsxFromSheets_, gasFormatDate_ };' : ''
  ];
  return parts.join('\n');
}

mkdirSync(join(here, 'dist'), { recursive: true });
const targets = forTest
  ? [['do', 'worker.test.mjs'], ['d1', 'hello-world.test.mjs']]
  : [['do', 'worker.js'], ['d1', 'hello-world.js']];
for (const [kind, name] of targets) {
  const out = bundle(kind, forTest);
  const file = join(here, 'dist', name);
  writeFileSync(file, out);
  console.log('Built ' + file + ' (' + Math.round(out.length / 1024) + ' KB, ' + names.length + ' functions)');
}
// Copy for pasting into the Cloudflare dashboard editor (kept in git so it can be copied from GitHub).
if (!forTest) writeFileSync(join(here, 'hello-world.js'), bundle('d1', false));
